const messages = { en, 'zh-CN': zhCN };
const dateOptions = { year: 'numeric', month: 'short', day: 'numeric' };
const timestampOptions = { dateStyle: 'medium', timeStyle: 'short' };

export function createTranslator(locale = DEFAULT_LOCALE) {
  const catalog = Object.hasOwn(messages, locale) ? messages[locale] : en;
  return (key, values = {}) => {
    const message = Object.hasOwn(catalog, key) ? catalog[key] : Object.hasOwn(en, key) ? en[key] : key;
    return message.replace(/\{(\w+)\}/g, (token, name) => Object.hasOwn(values, name) ? String(values[name]) : token);
  };
}

export function createFormatters(locale = DEFAULT_LOCALE) {
  const intlLocale = locale !== DEFAULT_LOCALE && Object.hasOwn(LOCALES, locale) ? locale : 'en-US';
  const dates = new Map();
  const numbers = new Map();

  function formatDate(value, options) {
    const key = JSON.stringify(options);
    if (!dates.has(key)) dates.set(key, new Intl.DateTimeFormat(intlLocale, { ...options, timeZone: 'America/Los_Angeles' }));
    return dates.get(key).format(value);
  }

  return {
    // The source stores local calendar days as ISO date-only strings. Noon UTC
    // falls on the same calendar day in Las Vegas throughout the year.
    date: (iso, options = dateOptions) => formatDate(new Date(`${iso}T12:00:00Z`), options),
    timestamp: (value, options = timestampOptions) => formatDate(new Date(value), options),
    number(value, options = {}) {
      const key = JSON.stringify(options);
      if (!numbers.has(key)) numbers.set(key, new Intl.NumberFormat(intlLocale, options));
      return numbers.get(key).format(value);
    },
  };
}
